/**
 * Where uploaded files live on disk, and the one mapping between a stored
 * FileUrl and a file.
 *
 * Local disk for now. The database never holds a disk path - only the URL
 * path the API serves the file from (UPLOADS_PATH + the file's place under
 * UPLOAD_DIR) - so moving to blob storage later means changing this file and
 * the static mount in app.js, not migrating every row.
 */
import { mkdir, writeFile, unlink } from 'node:fs/promises';
import { join, resolve, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { env } from '../config/env.js';
import { UPLOADS_PATH } from '../enums/index.js';
import { logger } from './logger.js';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Absolute. A relative UPLOAD_DIR resolves against the project, not the cwd. */
export const UPLOAD_ROOT = resolve(PROJECT_ROOT, env.UPLOAD_DIR);

/** The folder the employee uploads are served from. */
export const EMPLOYEE_UPLOAD_ROOT = join(UPLOAD_ROOT, 'employees');

/**
 * The file a FileUrl names, or null when the URL is not one of ours.
 *
 * Resolved and then checked to still be inside the folder: a FileUrl comes
 * out of the database, and "../" in one must never reach outside it.
 */
function diskPathFor(fileUrl) {
  if (typeof fileUrl !== 'string' || !fileUrl.startsWith(`${UPLOADS_PATH.EMPLOYEES}/`)) {
    return null;
  }
  const relative = fileUrl.slice(UPLOADS_PATH.EMPLOYEES.length + 1);
  const full = resolve(EMPLOYEE_UPLOAD_ROOT, relative);
  return full.startsWith(EMPLOYEE_UPLOAD_ROOT + sep) ? full : null;
}

/**
 * Writes one employee's file and returns the FileUrl to store.
 * `fileName` is generated by the caller, never taken from the upload.
 */
export async function storeEmployeeFile(employeeDetailId, fileName, buffer) {
  const folder = join(EMPLOYEE_UPLOAD_ROOT, String(employeeDetailId));
  await mkdir(folder, { recursive: true });
  // `wx`: a generated name that somehow exists already is a bug, not a file
  // to overwrite.
  await writeFile(join(folder, fileName), buffer, { flag: 'wx' });
  return `${UPLOADS_PATH.EMPLOYEES}/${employeeDetailId}/${fileName}`;
}

/**
 * Removes the file behind a FileUrl. Best effort, and never throws: it runs
 * after the database has already moved on, and a leftover file is a cleanup
 * job, not a reason to fail a request that succeeded.
 */
export async function removeStoredFile(fileUrl) {
  const path = diskPathFor(fileUrl);
  if (!path) return;
  try {
    await unlink(path);
  } catch (error) {
    if (error.code !== 'ENOENT') logger.warn(`Could not remove uploaded file ${fileUrl}`, error);
  }
}
